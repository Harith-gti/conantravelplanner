const UNSPLASH_KEY = (window.CX_CONFIG || {}).unsplashKey || '';
let PH = {};
try {
  PH = JSON.parse(localStorage.getItem('cx_photos')) || {};
} catch {}
async function photoFor(d) {
  const q = `${d.n} ${d.co || ''} travel`.trim();
  if (UNSPLASH_KEY) {
    if (PH[q]) return PH[q];
    try {
      const r = ((
        await jget(
          `https://api.unsplash.com/search/photos?per_page=1&orientation=landscape&query=${encodeURIComponent(q)}&client_id=${UNSPLASH_KEY}`,
        )
      ).results || [])[0];
      if (r) {
        PH[q] = {
          src: r.urls.small,
          by: r.user.name,
          link: r.links.html + '?utm_source=conan_travel_planner&utm_medium=referral',
        };
        localStorage.setItem('cx_photos', JSON.stringify(PH));
        return PH[q];
      }
    } catch {}
  }
  return {
    src: `https://tse2.mm.bing.net/th?q=${encodeURIComponent(q)}&w=640&h=420&c=7&rs=1&p=0`,
    by: '',
    link: '',
  };
}

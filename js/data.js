function ctRow(co) {
  const c = (co || '').toLowerCase();
  if (!c || (c.includes('north') && c.includes('korea'))) return null;
  const a = Object.keys(AL).find(k => c.includes(k)),
    k = a ? AL[a] : Object.keys(CT).find(x => c.includes(x.toLowerCase()));
  return k ? CT[k] : null;
}
const estCost = (d, days) => {
  const r = ctRow(d.co);
  return r ? Math.round((r[0] * days * [0.8, 1, 1.3][d.c - 1] + r[1]) / 10) * 10 : null;
};

